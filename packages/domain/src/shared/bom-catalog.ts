function slugifyPartNumber(partNumber: string): string {
  return partNumber
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function buildCatalog(): BomCatalogItem[] {
  const items: BomCatalogItem[] = [];
  const usedIds = new Set<string>();
  for (const clusterKey of BOM_CLUSTER_KEYS) {
    for (const [description, partNumber, manufacturer, flags] of BOM_ROWS[clusterKey]) {
      let partId = slugifyPartNumber(partNumber);
      let suffix = 2;
      while (usedIds.has(partId)) {
        partId = `${slugifyPartNumber(partNumber)}-${suffix}`;
        suffix += 1;
      }
      usedIds.add(partId);
      items.push({
        partId,
        description,
        partNumber,
        manufacturer,
        clusterKey,
        in660T: (flags & 1) !== 0,
        in50T: (flags & 2) !== 0,
      });
    }
  }
  return items;
}

export const bomCatalog: BomCatalogItem[] = buildCatalog();

export function getBomItemsByCluster(clusterKey: BomClusterKey): BomCatalogItem[] {
  return bomCatalog.filter((item) => item.clusterKey === clusterKey);
}

export function getBomCraneIds(item: BomCatalogItem): string[] {
  const ids: string[] = [];
  if (item.in660T) ids.push('crane-660t');
  if (item.in50T) ids.push('crane-50t');
  return ids;
}
