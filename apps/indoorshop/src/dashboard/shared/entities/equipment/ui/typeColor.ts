import { equipmentTypeOf } from '../index'

/*
 * 설비 종류의 **화면색** — 레지스트리 색과 화면에 칠하는 색을 잇는 한 겹.
 *
 * `typeLabel.ts` 와 같은 자리, 같은 이유의 파일이다. 레지스트리(`equipmentFixture`)의
 * `color` 는 도면 대조용으로 고른 값이고 **생성물이라 손으로 고칠 수 없다**(빌드 때
 * 다시 구워진다). 그런데 그 값 그대로는 화면에서 두 가지를 못 한다:
 *
 *  1. **캐비닛(#37474f)과 Edge PC(#5d6d7e)가 서로 안 갈린다.** 둘 다 채도 낮은 청회색
 *     이라 12px 심볼에서는 같은 회색 상자다. 배치도에 종류색을 넣은 뜻이 이 둘에서
 *     사라진다 — 사용자가 지적한 바로 그 지점이다.
 *  2. **어두운 관제 화면에서 바탕에 잠긴다.** 두 색 모두 흰 종이를 기준으로 고른 값이라
 *     다크 바탕(#23262c)과의 명도차가 거의 없다.
 *
 * 그래서 이 파일이 **화면에 칠할 색만** 갈아 끼운다. 규칙은 라벨 층과 같다:
 *  · 화면색이 정해진 종류는 그 값을 낸다.
 *  · 정해지지 않은 종류는 레지스트리 색을 그대로 쓴다(없는 색을 지어내지 않는다).
 *
 * ── 고를 때의 제약 ──
 *  · **상태색 자리를 넘보지 않는다.** 초록·앰버·빨강은 `statusPalette` 의 뜻이라
 *    종류색으로 쓰지 않는다. (자리로도 갈린다 — 종류색은 판, 상태색은 어깨의 부호.)
 *  · **강조색(오렌지) 을 쓰지 않는다.** 그 색은 '고른 것' 의 뜻이다.
 *  · **흰 글리프가 얹힌다.** 판이 너무 밝으면 글리프가 사라지므로 중간 명도로 고른다
 *    (흰색 대비 4:1 안팎). 동시에 어두운 바탕과도 떠야 하므로 채도를 높인다.
 *  · 서로 **보색에 가깝게** — 청록(캐비닛) ↔ 자홍(Edge PC) ↔ 보라(라이다)는 12px 에서도
 *    갈린다. 명도만 다른 색을 나란히 두면 작은 심볼에서는 결국 같은 회색이 된다.
 */

/** 화면색이 따로 정해진 종류 — 그 밖의 종류는 레지스트리 색 그대로 */
const DISPLAY_COLOR: Readonly<Record<string, string>> = {
  /* 네트워크 판넬 — 청록. 레지스트리 #37474f 는 다크 바탕과 명도차가 거의 없다 */
  PNL: '#0e8390',
  /* Edge PC — 자홍. 레지스트리 #5d6d7e 는 판넬과 같은 청회색이라 둘이 안 갈렸다 */
  EDGE: '#b0508f',
}

/** 이 종류에 화면색이 따로 있는가 */
export function hasEquipmentTypeColor(typeId: string): boolean {
  return typeId in DISPLAY_COLOR
}

/**
 * 종류ID → 화면에 칠할 색.
 *
 * 지도 심볼·목록 칩·범례가 **모두 이 값**을 쓴다 — 한 곳이라도 레지스트리 색을 직접
 * 읽으면 같은 설비가 화면마다 다른 색이 되고, 그 순간 "지도의 저 표시 = 목록의 이 줄"이
 * 성립하지 않는다.
 */
export function equipmentTypeColorOf(typeId: string): string {
  return DISPLAY_COLOR[typeId] ?? equipmentTypeOf(typeId)?.color ?? '#7a8794'
}
