/*
 * 베이 상세 카드의 **지번 짚기** — 두 상태가 한 값으로 합쳐지는 자리.
 *
 * 목록의 지번 줄은 두 가지를 할 수 있다: 손을 얹으면 지도가 그 칸을 잠시 짚어 보이고
 * (미리보기), 누르면 그 짚기가 남는다(고정). 지도는 그 둘을 합친 **하나**만 보면 되지만,
 * 목록의 줄은 **고정된 것만** 눌린 형태여야 한다 — 미리보기까지 섞으면 손이 얹힌 줄이
 * 이미 눌린 것으로 보여 다음 클릭이 해제가 되고, 그 줄은 영영 고정할 수 없는 버튼이 된다.
 *
 * 한 줄짜리 규칙이지만 화면에 흩어 두면 그 두 축이 다시 섞인다(실제로 한 번 섞였다).
 * 이름을 붙여 여기 모으고, 두 소비자(대시보드 지도·도장 배치도)가 같은 것을 부른다.
 */

/**
 * 지번 줄 클릭 — 이미 고정한 것을 다시 누르면 푼다(토글).
 *
 * 짚기는 드릴다운 단계가 아니다(`mapSpotlight` 의 선택 전이와 무관하다). 카메라도 움직이지
 * 않고 무엇을 골랐는지도 바꾸지 않으므로, 베이 재클릭으로 상세에 들어가는 길과 다투지 않는다.
 */
export function toggleSpottedLot(spotted: string | null, lot: string): string | null {
  return spotted === lot ? null : lot
}

/**
 * 지도가 지금 짚을 지번 — **미리보기가 고정보다 세다.**
 *
 * 목록을 훑는 동안은 손이 얹힌 칸이 답이어야 하고(그러라고 얹는 것이다), 손을 떼면
 * 고정해 둔 자리로 되돌아온다. 둘 다 없으면 지도는 아무것도 짚지 않는다.
 */
export function spotlitLot(spotted: string | null, previewed: string | null): string | null {
  return previewed ?? spotted
}
